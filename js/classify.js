export const CATEGORIES = ['餐饮','交通','购物','学习教育','娱乐休闲',
  '话费通讯','生活缴费','医疗健康','人情往来','其他'];

// 支付宝原始"交易分类" -> 统一分类
const ALIPAY_CATEGORY_MAP = {
  '餐饮美食':'餐饮','交通出行':'交通','日用百货':'购物','服饰装扮':'购物',
  '数码电器':'购物','文化休闲':'娱乐休闲','教育培训':'学习教育',
  '充值缴费':'生活缴费','医疗健康':'医疗健康','美容美发':'购物','母婴亲子':'购物',
  '生活服务':'生活缴费','商业服务':'其他','住房物业':'生活缴费',
  '运动户外':'娱乐休闲','酒店旅游':'娱乐休闲','转账红包':'人情往来'
};

// 关键词规则（命中 counterparty 或 description 即归类），顺序优先
const KEYWORD_RULES = [
  ['餐饮', ['美团','饿了么','瑞幸','蜜雪','星巴克','餐','外卖','奶茶','咖啡','食堂','乡村基']],
  ['交通', ['地铁','公交','轨道交通','高德','滴滴','打车','单车','火车','12306','出行']],
  ['学习教育', ['打印','文印','图书','书店','文具','培训','教育','学费','考试','报名']],
  ['娱乐休闲', ['Steam','Valve','游戏','会员','视频','音乐','电影','网吧']],
  ['购物', ['淘宝','天猫','京东','拼多多','超市','便利店','服饰','旗舰店']],
  ['话费通讯', ['话费','流量','移动','联通','电信','宽带']],
  ['生活缴费', ['校园卡','一卡通','充值','水费','电费','宿舍']],
  ['人情往来', ['转账','红包']],
];

export function classify(t, memory = {}) {
  // 1. 商户记忆优先
  if (t.counterparty && memory[t.counterparty]) return memory[t.counterparty];
  // 2. 支付宝原始分类映射
  if (t.source === '支付宝' && ALIPAY_CATEGORY_MAP[t.rawCategory])
    return ALIPAY_CATEGORY_MAP[t.rawCategory];
  // 3. 关键词规则
  const hay = `${t.counterparty} ${t.description}`;
  for (const [cat, words] of KEYWORD_RULES)
    if (words.some(w => hay.includes(w))) return cat;
  // 4. 兜底
  return '其他';
}
